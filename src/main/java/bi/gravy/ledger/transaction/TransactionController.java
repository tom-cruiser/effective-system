package bi.gravy.ledger.transaction;

import static bi.gravy.ledger.common.errors.ErrorCode.ACCESS_DENIED;
import static bi.gravy.ledger.common.errors.ErrorCode.ACCOUNT_FROZEN;
import static bi.gravy.ledger.common.errors.ErrorCode.ACCOUNT_NOT_FOUND;
import static bi.gravy.ledger.common.errors.ErrorCode.ALREADY_REVERSED;
import static bi.gravy.ledger.common.errors.ErrorCode.CURRENCY_MISMATCH;
import static bi.gravy.ledger.common.errors.ErrorCode.IDEMPOTENCY_CONFLICT;
import static bi.gravy.ledger.common.errors.ErrorCode.INSUFFICIENT_FUNDS;
import static bi.gravy.ledger.common.errors.ErrorCode.SAME_ACCOUNT_TRANSFER;
import static bi.gravy.ledger.common.errors.ErrorCode.TRANSACTION_NOT_FOUND;

import bi.gravy.ledger.common.errors.ApiErrors;
import bi.gravy.ledger.common.idempotency.IdempotencyKeys;
import bi.gravy.ledger.security.AccessGuard;
import bi.gravy.ledger.transaction.dto.PayoutRequest;
import bi.gravy.ledger.transaction.dto.ReversalRequest;
import bi.gravy.ledger.transaction.dto.RidePaymentRequest;
import bi.gravy.ledger.transaction.dto.TopUpRequest;
import bi.gravy.ledger.transaction.dto.TransactionResponse;
import bi.gravy.ledger.transaction.dto.TransferRequest;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.net.URI;
import java.util.UUID;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/transactions")
@Tag(name = "Transactions")
public class TransactionController {

  private static final String IDEMPOTENCY_KEY_DOC =
      "Unique per logical operation (e.g. a UUID generated by the client). Retrying with the same"
          + " key and body returns the original transaction with 200 instead of 201.";

  private final TransactionService transactionService;
  private final AccessGuard accessGuard;

  public TransactionController(TransactionService transactionService, AccessGuard accessGuard) {
    this.transactionService = transactionService;
    this.accessGuard = accessGuard;
  }

  @PostMapping("/top-ups")
  @Operation(summary = "Credit a wallet with money received through mobile money")
  @ApiResponse(responseCode = "201", description = "Posted")
  @ApiResponse(
      responseCode = "200",
      description =
          "Replay: same Idempotency-Key and body as an earlier request, which is returned")
  @ApiErrors({
    ACCESS_DENIED,
    ACCOUNT_NOT_FOUND,
    ACCOUNT_FROZEN,
    CURRENCY_MISMATCH,
    IDEMPOTENCY_CONFLICT
  })
  public ResponseEntity<TransactionResponse> topUp(
      @Parameter(description = IDEMPOTENCY_KEY_DOC) @RequestHeader(IdempotencyKeys.HEADER)
          String idempotencyKey,
      @Valid @RequestBody TopUpRequest request) {
    accessGuard.requireAccountAccess(request.accountId());
    return respond(transactionService.topUp(request, IdempotencyKeys.requireValid(idempotencyKey)));
  }

  @PostMapping("/transfers")
  @Operation(summary = "Move money from one wallet to another")
  @ApiResponse(responseCode = "201", description = "Posted")
  @ApiResponse(
      responseCode = "200",
      description =
          "Replay: same Idempotency-Key and body as an earlier request, which is returned")
  @ApiErrors({
    ACCESS_DENIED,
    ACCOUNT_NOT_FOUND,
    ACCOUNT_FROZEN,
    CURRENCY_MISMATCH,
    INSUFFICIENT_FUNDS,
    SAME_ACCOUNT_TRANSFER,
    IDEMPOTENCY_CONFLICT
  })
  public ResponseEntity<TransactionResponse> transfer(
      @Parameter(description = IDEMPOTENCY_KEY_DOC) @RequestHeader(IdempotencyKeys.HEADER)
          String idempotencyKey,
      @Valid @RequestBody TransferRequest request) {
    // Only the sender's account must be the caller's; anyone can receive money.
    accessGuard.requireAccountAccess(request.fromAccountId());
    return respond(
        transactionService.transfer(request, IdempotencyKeys.requireValid(idempotencyKey)));
  }

  @PostMapping("/ride-payments")
  @Operation(
      summary = "Pay for a ride",
      description =
          "Debits the rider for the full fare, credits the driver with the fare minus the platform"
              + " fee and credits PLATFORM_FEES with the fee (ledger.platform-fee-bps, rounded"
              + " down).")
  @ApiResponse(responseCode = "201", description = "Posted")
  @ApiResponse(
      responseCode = "200",
      description =
          "Replay: same Idempotency-Key and body as an earlier request, which is returned")
  @ApiErrors({
    ACCESS_DENIED,
    ACCOUNT_NOT_FOUND,
    ACCOUNT_FROZEN,
    CURRENCY_MISMATCH,
    INSUFFICIENT_FUNDS,
    IDEMPOTENCY_CONFLICT
  })
  public ResponseEntity<TransactionResponse> ridePayment(
      @Parameter(description = IDEMPOTENCY_KEY_DOC) @RequestHeader(IdempotencyKeys.HEADER)
          String idempotencyKey,
      @Valid @RequestBody RidePaymentRequest request) {
    accessGuard.requireAccountAccess(request.riderAccountId());
    return respond(
        transactionService.ridePayment(request, IdempotencyKeys.requireValid(idempotencyKey)));
  }

  @PostMapping("/payouts")
  @Operation(summary = "Pay a driver out to mobile money")
  @ApiResponse(responseCode = "201", description = "Posted")
  @ApiResponse(
      responseCode = "200",
      description =
          "Replay: same Idempotency-Key and body as an earlier request, which is returned")
  @ApiErrors({
    ACCESS_DENIED,
    ACCOUNT_NOT_FOUND,
    ACCOUNT_FROZEN,
    CURRENCY_MISMATCH,
    INSUFFICIENT_FUNDS,
    IDEMPOTENCY_CONFLICT
  })
  public ResponseEntity<TransactionResponse> payout(
      @Parameter(description = IDEMPOTENCY_KEY_DOC) @RequestHeader(IdempotencyKeys.HEADER)
          String idempotencyKey,
      @Valid @RequestBody PayoutRequest request) {
    accessGuard.requireAccountAccess(request.driverAccountId());
    return respond(
        transactionService.payout(request, IdempotencyKeys.requireValid(idempotencyKey)));
  }

  @PostMapping("/{id}/reversal")
  @Operation(
      summary = "Reverse a transaction (ADMIN only)",
      description = "Posts the exact opposite entries. A transaction can be reversed only once.")
  @ApiResponse(responseCode = "201", description = "Posted")
  @ApiResponse(
      responseCode = "200",
      description =
          "Replay: same Idempotency-Key and body as an earlier request, which is returned")
  @ApiErrors({
    ACCESS_DENIED,
    TRANSACTION_NOT_FOUND,
    ALREADY_REVERSED,
    INSUFFICIENT_FUNDS,
    ACCOUNT_FROZEN,
    IDEMPOTENCY_CONFLICT
  })
  public ResponseEntity<TransactionResponse> reverse(
      @PathVariable UUID id,
      @Parameter(description = IDEMPOTENCY_KEY_DOC) @RequestHeader(IdempotencyKeys.HEADER)
          String idempotencyKey,
      @Valid @RequestBody(required = false) ReversalRequest request) {
    return respond(
        transactionService.reverse(id, request, IdempotencyKeys.requireValid(idempotencyKey)));
  }

  @GetMapping("/{id}")
  @Operation(summary = "Get a transaction and its postings")
  @ApiErrors({ACCESS_DENIED, TRANSACTION_NOT_FOUND})
  public TransactionResponse get(@PathVariable UUID id) {
    PostedTransaction posted = transactionService.get(id);
    accessGuard.requireAnyAccountAccess(
        posted.postings().stream().map(Posting::getAccountId).toList());
    return TransactionResponse.from(posted);
  }

  /** 201 with a Location for a new transaction; 200 for an idempotent replay of an old one. */
  private static ResponseEntity<TransactionResponse> respond(PostedTransaction posted) {
    TransactionResponse body = TransactionResponse.from(posted);
    if (posted.replayed()) {
      return ResponseEntity.ok(body);
    }
    return ResponseEntity.created(URI.create("/api/v1/transactions/" + body.id())).body(body);
  }
}
